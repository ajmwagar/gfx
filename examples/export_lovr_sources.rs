//! Deterministically freeze bounded shared shaders for hosts with older native plugins.
use sha2::{Digest, Sha256};
use std::{error::Error, fmt::Write, fs, path::PathBuf};
fn main() -> Result<(), Box<dyn Error>> {
    let mut args = std::env::args().skip(1);
    let first = args
        .next()
        .ok_or("output directory or --check directory required")?;
    let check = first == "--check";
    let root = PathBuf::from(if check {
        args.next().ok_or("check directory required")?
    } else {
        first
    });
    if args.next().is_some() {
        return Err("unexpected arguments".into());
    }
    if !check {
        fs::create_dir_all(&root)?;
    }
    let write_or_check = |name: &str, expected: &[u8]| -> Result<(), Box<dyn Error>> {
        let path = root.join(name);
        if check {
            if fs::read(&path)? != expected {
                return Err(format!("GFX source drift: {}", path.display()).into());
            }
        } else {
            fs::write(path, expected)?;
        }
        Ok(())
    };
    let mut sources = Vec::new();
    let mut lua = String::from(
        "-- Generated by fpl-gfx export_lovr_sources; do not edit.\nreturn {abi=1,shaders={\n",
    );
    for &name in fpl_gfx::lovr::FROZEN_SHADERS {
        let source = fpl_gfx::lovr::shader(name).ok_or("unknown shared shader")?;
        let file = format!("{name}.frag");
        let digest = format!("{:x}", Sha256::digest(source.fragment.as_bytes()));
        write_or_check(&file, source.fragment.as_bytes())?;
        writeln!(
            lua,
            "[\"{name}\"]={{vertex=\"{}\",fragment=\"assets/gfx/{file}\",sha256=\"{digest}\"}},",
            source.vertex
        )?;
        sources.push(serde_json::json!({"name":name,"vertex":source.vertex,"fragment":file,"sha256":digest,"origin":format!("https://github.com/ajmwagar/gfx/blob/main/src/lovr/{file}")}));
    }
    lua.push_str("},symbols={\n");
    for &name in fpl_gfx::lovr::FROZEN_SYMBOLS {
        write!(lua, "[\"{name}\"]={{")?;
        for point in fpl_gfx::symbols::outline(name).ok_or("missing outline")? {
            write!(lua, "{{{}, {}}},", point[0], point[1])?;
        }
        lua.push_str("},\n");
    }
    lua.push_str("}}\n");
    write_or_check("catalog.lua", lua.as_bytes())?;
    let receipt = serde_json::to_vec_pretty(
        &serde_json::json!({"schema":"fpl.gfx.lovr-source-snapshot.v1","abi":fpl_gfx::lovr::ABI_VERSION,"generator":"fpl-gfx/examples/export_lovr_sources.rs","sources":sources}),
    )?;
    // Older host bundles have no receipt. Check their immutable source/catalog
    // bytes; when a receipt exists it must match too.
    if !check || root.join("receipt.json").exists() {
        write_or_check("receipt.json", &receipt)?;
    }
    Ok(())
}
